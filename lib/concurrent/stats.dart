/// ============================================================================
/// 统计指标（仅用于演示面板展示整个漏斗的实时水位）
/// ----------------------------------------------------------------------------
/// 不介入业务逻辑，只被各层累加计数，方便直观看到「洪峰如何被削平」。
/// ============================================================================
class RoomStats {
  /// 已接收原始消息（来自模拟器 / 长连接）
  int received = 0;

  /// Isolate 解析成功
  int parsed = 0;

  /// Isolate 解析失败（脏数据）
  int failed = 0;

  /// 当前排队中的消息
  int queued = 0;

  /// 已分发到 UI 的总消息
  int dispatched = 0;

  /// 去重丢弃（重复 seq）
  int dropped = 0;

  /// 公屏当前显示条数
  int chat = 0;

  void reset() {
    received = 0;
    parsed = 0;
    failed = 0;
    queued = 0;
    dispatched = 0;
    dropped = 0;
    chat = 0;
  }
}
